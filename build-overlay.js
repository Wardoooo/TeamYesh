import { readFileSync, writeFileSync } from "node:fs";
import { posix } from "node:path";

const modules = new Map();
const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const styles = ["overlay/overlay.css", "overlay/ads.css", "overlay/popups.css"]
  .map(path => read(path).replace(/\r\n/g, "\n"))
  .join("\n");

function include(path) {
  if (modules.has(path)) return;
  const names = [];
  const source = read(path)
    .replace(/^import \{ ([^}]+) \} from "([^"]+)";$/gm, (_, bindings, relative) => {
      const dependency = posix.join(posix.dirname(path), relative);
      include(dependency);
      return `const { ${bindings.replace(/ as /g, ": ")} } = modules[${JSON.stringify(dependency)}];`;
    })
    .replace(/^export (const|function|async function) (\w+)/gm, (_, kind, name) => {
      names.push(name);
      return `${kind} ${name}`;
    })
    .replaceAll("import.meta.url", `chrome.runtime.getURL(${JSON.stringify(path)})`)
    .replace(/async function loadCss\(style\) \{[\s\S]*?\n\}/, () =>
      `function loadCss(style) { style.textContent = ${JSON.stringify(styles)}; }`);
  modules.set(path, `modules[${JSON.stringify(path)}] = (() => {\n${source}\nreturn { ${names.join(", ")} };\n})();`);
}

include("overlay/overlay.js");
writeFileSync(new URL("overlay/content-loader.js", import.meta.url), `// Generated by node build-overlay.js.
chrome.runtime.sendMessage({ type: "getState" }).then(({ state }) => {
  if (!state || !["ads", "captcha", "browsing"].includes(state.phase)) return;
  const modules = {};
${[...modules.values()].join("\n")}
}).catch((error) => console.error("Pisonet overlay failed to load:", error));
`);
